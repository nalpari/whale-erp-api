## 위치정보의 전달

출퇴근 화면에 지도를 보여 주려고 카카오 지도(주식회사 카카오)에서 내 주변 지도를 받아 옵니다. 이때 대략적인 위치(지도에 보이는 영역)가 카카오에 전달됩니다. 좌표는 회사 서버로 보내거나 저장하지 않습니다. [제공 · 위탁 해당 여부는 법무 확인]

## 판정 결과의 제공

판정 결과(반경 안 · 확인 필요)와 등록 시각은 출퇴근 관리를 위해 소속 사업장의 관리자에게 보입니다. 좌표는 제공하지 않습니다. [제3자 제공 해당 여부와 즉시 통보 방식은 법무 확인]

