## 수집 방법과 시점

1. 출퇴근 탭에 들어올 때와 출근·퇴근 버튼을 누를 때 한 번씩 위치를 확인합니다. 출근·퇴근 판정은 버튼을 누를 때 확인한 위치로 합니다.
2. 앱을 쓰지 않는 동안이나 근무 중에 위치를 계속 추적하지 않습니다.
3. 근무지 반경은 기본 100m 이며, 지하·실내 근무지는 관리자가 넓힐 수 있습니다.

