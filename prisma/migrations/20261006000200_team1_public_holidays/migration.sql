-- 공식 휴일 1346행 (2000~2100).
--
-- 「관공서의 공휴일에 관한 규정」으로 계산한 결과다. 손으로 쓰지 않았고, 계산기는
-- 일회용이라 저장소에 두지 않았다 — 그래서 **아래에 규칙 전체를 적어 둔다.** 다시
-- 만들어야 하면 이 주석이 명세다. 적용된 마이그레이션은 되돌지 않으므로, 규칙이
-- 바뀌면 이 파일을 고치지 말고 새 마이그레이션을 쓴다.
--
-- ── 양력 10종 (적용 연도) ──
--   신정 1/1 · 삼일절 3/1 · 어린이날 5/5 · 현충일 6/6 · 광복절 8/15 ·
--   개천절 10/3 · 성탄절 12/25        → 전체 연도
--   식목일 4/5                         → 2005년까지
--   제헌절 7/17                        → 2007년까지
--   한글날 10/9                        → 2013년부터
--
-- ── 음력 3종 ──
--   설날   음 12월 말일 · 1/1 · 1/2 사흘. 음 12월이 29일인 해도 30일인 해도 있어
--          말일을 세지 않고 음 1/1 에서 하루를 뺀다.
--   부처님오신날  음 4/8
--   추석   음 8/14 · 8/15 · 8/16 사흘 (같은 이유로 음 8/15 앞뒤 하루)
--   변환은 한국천문연구원 기준이고, 그 표가 2050-11-18 까지라
--   **2051~2100 은 양력만 들어 있다**. 2050년까지 859행, 그 뒤 487행.
--   모자란 음력분은 공공 API 동기화로 받는다.
--
-- ── 대체공휴일 189행 ──
--   설날 · 추석        일요일과 겹치거나 다른 공휴일과 겹치면      → 2014년부터
--   어린이날           토·일요일 또는 다른 공휴일과 겹치면        → 2014년부터
--   삼일절·광복절·개천절·한글날   토·일요일과 겹치면              → 2021년부터
