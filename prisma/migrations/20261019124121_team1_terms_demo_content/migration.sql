## 제3조 (약관의 게시와 개정)

1. 회사는 이 약관을 서비스 초기 화면과 홈페이지에 게시합니다.
2. 회사는 관련 법령을 위반하지 않는 범위에서 약관을 개정할 수 있으며, 적용일 7일 전부터 공지합니다. 회원에게 불리한 개정은 적용일 30일 전부터 공지하고 등록된 이메일로 따로 알립니다.
3. 회원이 적용일까지 거부 의사를 밝히지 않으면 개정 약관에 동의한 것으로 봅니다. 동의하지 않는 회원은 이용계약을 해지할 수 있습니다.

## 제4조 (이용계약의 성립)

1. 이용계약은 가입 신청자가 이 약관과 개인정보 수집·이용에 동의하고 가입을 신청한 뒤 회사가 승낙하면 성립합니다.
2. 회사나 회원이 대신 등록한 계정은 이용자가 최초 로그인 때 이 약관에 동의하면 그 이용자에게 효력이 생깁니다.
3. 회사는 타인의 명의나 허위 정보로 신청한 경우, 이전에 이 약관 위반으로 계약이 해지된 경우, 그 밖에 관련 법령을 위반한 경우 승낙하지 않거나 사후에 이용계약을 해지할 수 있습니다.

## 제5조 (회원 정보의 변경)

회원은 등록한 정보가 바뀌면 지체 없이 서비스에서 수정해야 합니다. 수정하지 않아 생긴 불이익은 회원이 부담합니다.

## 제6조 (회사의 의무)

1. 회사는 관련 법령과 이 약관이 금지하는 행위를 하지 않으며, 서비스를 안정적으로 제공하기 위해 노력합니다.
2. 회사는 회원 데이터를 보호하기 위해 보안 체계를 갖추고, 개인정보처리방침을 공개하고 지킵니다.
3. 회사는 회원의 정당한 의견이나 불만을 신속히 처리하고 처리 결과를 알립니다.

## 제7조 (회원과 이용자의 의무)

1. 회원과 이용자는 계정을 제3자에게 알리거나 빌려주어서는 안 되며, 계정 관리 소홀로 생긴 책임을 집니다.
2. 회원은 서비스에 직원 등 제3자의 개인정보를 입력할 때 관련 법령에 따른 동의나 법적 근거를 스스로 갖추어야 합니다.
3. 회원과 이용자는 허위 정보 등록, 서비스의 역설계·무단 복제, 서비스 운영 방해, 타인의 권리 침해, 그 밖에 법령에 어긋나는 행위를 해서는 안 됩니다.

## 제8조 (서비스의 제공과 변경)

1. 회사는 연중무휴 1일 24시간 서비스를 제공하는 것을 원칙으로 합니다.
2. 회사는 서비스의 내용을 바꿀 수 있으며, 회원에게 중대한 영향을 주는 변경은 7일 전에 공지합니다.

## 제9조 (서비스의 중단)

1. 회사는 설비 점검·교체·장애, 통신 두절, 천재지변 등 부득이한 사유가 있으면 서비스를 일시 중단할 수 있습니다.
2. 계획된 중단은 미리 공지하고, 미리 알릴 수 없는 경우에는 사후에 알립니다.

## 제10조 (이용 요금)

1. 서비스의 요금과 결제 방법은 홈페이지의 요금 안내에 따릅니다. [요금 체계·결제 방식은 아직 확정 전이며, 부가서비스 구독·정산 기능도 1차 범위에 포함되지 않습니다.]
2. 회사가 무료로 제공하던 서비스를 유료로 바꾸는 경우 적용일 30일 전에 공지하고 개별 통지합니다. 회원은 유료 전환에 동의하지 않으면 이용계약을 해지할 수 있습니다.

## 제11조 (이용 제한)

1. 회사는 회원이나 이용자가 제7조를 위반하면 경고, 일시 정지, 이용계약 해지의 순서로 이용을 제한할 수 있습니다.
2. 명백한 불법 행위나 보안 위협이 있는 경우에는 즉시 제한할 수 있습니다.
3. 회사는 제한 사유와 기간을 알리고, 회원은 이의를 제기할 수 있습니다.

## 제12조 (계약 해지)

1. BP 마스터는 언제든지 MY PAGE 의 회원 탈퇴로 이용계약을 해지할 수 있습니다.
2. 회사는 제4조 제3항이나 제11조에 해당하면 이용계약을 해지할 수 있습니다.

## 제13조 (회원 데이터의 소유와 처리)

1. 회원 데이터의 권리는 회원에게 있습니다.
2. 회원 데이터 가운데 개인정보에 대해서는 회원이 개인정보처리자이고, 회사는 회원의 위탁을 받아 서비스 제공에 필요한 범위에서만 처리하는 수탁자입니다. 세부 사항은 개인정보 처리위탁 계약에 따릅니다.
3. 회사는 개인을 알아볼 수 없도록 가공한 통계 정보를 서비스 개선에 쓸 수 있습니다.
4. 이용계약이 끝나면 회원은 [30]일 동안 회원 데이터를 내려받을 수 있으며, 회사는 그 기간이 지나면 회원 데이터를 파기합니다. 다만 법령이 보존을 요구하는 정보는 정해진 기간 동안 분리 보관합니다.

## 제14조 (개인정보 처리위탁)

1. 회원이 서비스에 등록한 이용자(직원 등)의 개인정보에 대하여, 회사는 회원의 위탁을 받아 근태·근무스케줄·급여명세서 등 인사 정보의 저장·관리를 포함한 서비스 제공에 필요한 범위의 업무를 처리합니다.
2. 회사는 위탁받은 업무의 범위를 넘어 개인정보를 이용하거나 제3자에게 제공하지 않습니다.
3. 회사는 위탁받은 업무를 제3자에게 재위탁하지 않습니다. 다만 클라우드 인프라 등 서비스 운영에 반드시 필요한 처리를 위해 재위탁하는 경우에는 개인정보처리방침에 그 사실을 알립니다.
4. 회사는 위탁받은 개인정보를 안전하게 처리하기 위해 접근 권한 제한, 암호화, 접속 기록 보관 등 안전성 확보조치를 취합니다.
5. 회사가 위탁받은 업무를 처리하는 과정에서 고의 또는 과실로 개인정보를 분실·도난·유출·위조·변조 또는 훼손한 경우 회원과 이용자에게 생긴 손해를 배상하며, 배상 범위는 제17조를 따릅니다.
6. 회원과 회사가 개인정보 처리위탁에 관해 별도로 계약을 체결한 경우에는 그 계약을 우선합니다.

## 제15조 (개인정보 보호)

회사는 관련 법령과 개인정보처리방침에 따라 이용자의 개인정보를 보호합니다.

## 제16조 (지식재산권)

서비스와 관련된 소프트웨어, 디자인, 상표 등 지식재산권은 회사에 있습니다. 회원은 이 약관이 허용한 범위에서만 서비스를 이용할 수 있습니다.

## 제17조 (손해배상)

1. 회사나 회원이 이 약관을 위반하여 상대방에게 손해를 입히면 그 손해를 배상합니다.
2. 회사의 고의나 중대한 과실로 인한 손해가 아니면, 회사의 배상액은 손해가 발생하기 전 [12]개월 동안 회원이 낸 이용 요금 합계를 넘지 않습니다.

## 제18조 (면책)

1. 회사는 다음 사유로 생긴 손해에 대해서는 책임지지 않습니다. 다만 회사에 고의나 중대한 과실이 있으면 그렇지 않습니다.
2. 천재지변이나 이에 준하는 불가항력
3. 회원이나 이용자의 귀책사유로 인한 이용 장애
4. 회원이 입력한 정보의 오류
5. 제3자가 제공하는 서비스(국세청 사업자등록정보 진위확인 등)의 장애
6. 회원 사이, 회원과 이용자 사이의 분쟁

## 제19조 (통지)

1. 회사는 회원이 등록한 이메일과 서비스 안 알림으로 회원에게 통지합니다. 회원에게 가는 통지는 1차 범위에서 문자메시지를 쓰지 않습니다.
2. 전체 회원에 대한 통지는 서비스 공지사항에 7일 이상 게시하는 것으로 갈음할 수 있습니다.

## 제20조 (양도 금지)

회원은 이용계약상의 지위나 권리·의무를 회사의 동의 없이 제3자에게 양도하거나 담보로 제공할 수 없습니다.

## 제21조 (분리 가능성)

이 약관의 일부가 무효가 되어도 나머지 조항은 효력을 유지합니다.

## 제22조 (준거법과 관할)

이 약관은 대한민국 법률에 따르며, 분쟁에 관한 소송은 민사소송법에 따른 관할 법원에 제기합니다.

