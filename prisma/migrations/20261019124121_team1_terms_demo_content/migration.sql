## 제2조 (정의)

1. “근무 앱”이란 회사가 제공하는 웨일ERP 서비스 중 직원이 출퇴근 기록, 근무스케줄, 할 일(TO-DO), 급여명세서 등을 확인하거나 관리할 수 있는 모바일 애플리케이션을 말합니다.
2. “소속 사업장”이란 웨일ERP를 이용하는 사업자 회원(BP) 중 직원이 근로계약을 맺고 소속되어 있는 사업장을 말합니다.
3. “직원”이란 소속 사업장의 초대를 받아 근무 앱에 가입한 이용자를 말하며, 소속이 종료된 후 계정을 유지하는 이용자를 포함합니다.
4. “계정”이란 직원이 근무 앱을 이용하기 위해 등록한 식별정보와 인증정보 등을 말합니다.
5. “직원 데이터”란 직원 또는 소속 사업장이 근무 앱에 입력하거나 근무 앱 이용 과정에서 생성되는 직원 관련 정보를 말합니다.
6. “소속 사업장 관리자”란 소속 사업장으로부터 직원의 소속 및 이용 권한 등을 관리할 권한을 부여받은 사람을 말합니다.

## 제3조 (약관의 게시와 개정)

1. 회사는 직원이 이 약관을 쉽게 확인할 수 있도록 근무 앱의 가입 화면 및 설정 화면 등에 게시합니다.
2. 회사는 관련 법령을 위반하지 않는 범위에서 이 약관을 개정할 수 있습니다.
3. 회사는 약관을 개정하는 경우 개정 내용, 개정 사유 및 적용일을 명시하여 적용일 7일 전부터 공지합니다. 직원에게 불리하거나 직원의 권리·의무에 중대한 영향을 미치는 개정은 적용일 30일 전부터 공지하고, 제14조에 따른 방법으로 개별 통지합니다.
4. 회사가 개정 약관을 알리면서 적용일까지 거부 의사를 표시하지 않으면 동의한 것으로 본다는 뜻과 거부 방법을 명확하게 개별 통지한 경우, 직원이 해당 기간 내에 거부 의사를 표시하지 않으면 개정 약관에 동의한 것으로 봅니다. 다만, 관련 법령에 따라 명시적인 동의가 필요한 경우에는 별도로 동의를 받습니다.
5. 직원은 개정 약관에 동의하지 않는 경우 적용일 전까지 회사에 거부 의사를 표시하거나 이용계약을 해지할 수 있습니다. 회사는 기존 약관에 따른 서비스 제공이 어려운 경우 그 사유와 이용계약 종료 예정일을 사전에 알리고 이용계약을 종료할 수 있습니다.

## 제4조 (이용계약의 성립 및 소속 관리)

1. 이용계약은 소속 사업장의 초대를 받은 사람이 이 약관에 동의하고, 회사가 안내하는 본인확인 및 가입 절차를 완료하여 회사가 가입을 승인하면 성립합니다. 개인정보 처리에 별도의 동의가 필요한 경우 회사는 해당 동의를 구분하여 받습니다.
2. 직원 계정은 만 19세 이상인 사람만 만들 수 있습니다. 본인확인 결과 만 19세 미만인 경우 가입이 제한되며, 해당 직원의 근무관리는 소속 사업장이 근무 앱 외의 방법으로 처리합니다.
3. 직원의 소속 및 사업장별 이용 권한은 소속 사업장 관리자가 관리합니다. 여러 사업장에 소속되거나 소속 사업장을 변경하는 경우에는 회사가 안내하는 절차에 따릅니다.
4. 이미 가입한 직원이 다른 사업장의 초대를 받은 경우에는 기존 계정을 이용하여 소속 추가 또는 변경 절차를 진행할 수 있습니다.
5. 소속의 추가 또는 변경만으로 이전 사업장의 업무기록이 다른 사업장에 제공되지는 않습니다.

## 제5조 (계정관리 및 직원의 의무)

1. 직원은 자신의 계정과 인증정보를 안전하게 관리해야 하며, 이를 제3자에게 공유하거나 계정을 양도·대여해서는 안 됩니다.
2. 직원은 계정 도용 또는 무단 이용 사실을 알게 된 경우 지체 없이 회사에 알리고, 피해를 줄이기 위한 조치에 협조해야 합니다.
3. 직원은 가입 및 근무 앱 이용 과정에서 정확한 정보를 제공해야 하며, 다른 사람을 사칭하거나 근무기록 등을 허위로 입력해서는 안 됩니다.
4. 직원은 다른 사람의 정보를 무단으로 열람·수집·이용하거나, 접근 권한을 우회하거나, 근무 앱의 정상적인 운영을 방해해서는 안 됩니다.
5. 직원의 고의 또는 과실로 계정이 부정하게 이용되어 손해가 발생한 경우 책임은 관련 법령에 따라 정합니다.

## 제6조 (회사의 의무)

1. 회사는 관련 법령과 이 약관을 준수하고, 근무 앱을 안정적으로 제공하기 위해 노력합니다.
2. 회사는 개인정보를 보호하기 위해 관련 법령에 따른 기술적·관리적·물리적 안전조치를 시행하고, 개인정보처리방침을 공개하고 준수합니다.
3. 회사는 근무 앱 이용과 관련하여 직원이 제기한 정당한 의견이나 불만을 처리하고, 즉시 처리가 어려운 경우 그 사유와 처리 예정 일정을 안내합니다.
4. 회사는 직원 데이터에 대한 접근 권한을 업무상 필요한 범위로 관리하고, 무단 접근 및 유출을 방지하기 위한 조치를 시행합니다.

## 제7조 (서비스의 제공과 변경)

1. 회사는 연중무휴 1일 24시간 근무 앱을 제공하는 것을 원칙으로 합니다. 다만, 제8조에 따른 중단이 발생할 수 있습니다.
2. 직원이 이용할 수 있는 기능과 정보의 범위는 소속 사업장의 서비스 이용 범위 및 직원에게 부여된 권한에 따라 달라질 수 있습니다.
3. 회사는 서비스 개선, 보안 강화, 기술적 필요 또는 관련 법령의 변경 등 합리적인 사유가 있는 경우 근무 앱의 기능이나 제공 방식을 변경할 수 있습니다.
4. 회사는 직원의 이용에 중대한 영향을 미치는 변경이 있는 경우 변경 내용, 사유 및 적용일을 7일 전까지 공지합니다. 다만, 긴급한 보안 조치 등 사전에 공지하기 어려운 경우에는 변경 후 지체 없이 알립니다.
5. 근무기록의 승인, 근무스케줄의 편성, 급여 산정 및 지급 등 인사·노무 관련 사항은 소속 사업장이 담당합니다. 직원은 해당 내용의 확인이나 정정이 필요한 경우 소속 사업장에 요청할 수 있으며, 회사는 시스템 오류 등 회사가 담당하는 사항에 대해 필요한 조치를 합니다.

## 제8조 (서비스의 중단)

1. 회사는 설비 점검·교체, 시스템 장애, 통신 두절, 천재지변 등 부득이한 사유가 있는 경우 근무 앱의 전부 또는 일부를 일시 중단할 수 있습니다.
2. 계획된 중단은 중단 사유, 예정 시간 및 영향을 받는 기능을 미리 공지합니다. 사전에 알리기 어려운 경우에는 중단 후 지체 없이 알립니다.
3. 회사는 중단 사유가 해소되면 서비스를 신속하게 복구하기 위해 노력하고, 필요한 경우 복구 진행 상황을 안내합니다.

## 제9조 (이용 제한)

1. 회사는 직원이 제5조를 위반한 경우 위반의 내용, 정도 및 반복 여부 등을 고려하여 경고, 일시적인 이용 정지 또는 이용계약 해지 등의 조치를 할 수 있습니다.
2. 회사는 원칙적으로 이용 제한 사유, 범위, 기간 및 이의제기 방법을 사전에 통지합니다. 다만, 개인정보 유출, 계정 도용 또는 서비스에 대한 중대한 침해를 막기 위해 긴급한 조치가 필요한 경우에는 먼저 이용을 제한하고 지체 없이 통지할 수 있습니다.
3. 직원은 이용 제한 조치에 대해 회사가 안내하는 방법으로 이의를 제기할 수 있습니다. 회사는 이의제기 내용을 검토하고 그 결과를 알리며, 제한 사유가 해소되거나 조치가 잘못된 것으로 확인된 경우 필요한 조치를 합니다.
4. 소속 사업장과의 근로관계가 종료되면 해당 사업장에 대한 접근 권한은 종료됩니다. 다른 소속 사업장이 없는 경우 사업장 관련 기능의 이용은 제한되지만, 제10조에 따른 회원 탈퇴 등 계정관리 절차는 이용할 수 있습니다.

## 제10조 (이용계약의 해지 및 소속 종료)

1. 직원은 언제든지 근무 앱의 회원 탈퇴 기능을 통해 이용계약을 해지할 수 있습니다. 해당 기능을 이용하기 어려운 경우 회사가 안내하는 고객지원 창구를 통해 탈퇴를 요청할 수 있습니다.
2. 회사는 직원의 탈퇴 의사를 확인한 후 지체 없이 탈퇴를 처리합니다.
3. 소속 사업장과의 근로관계 종료는 근무 앱의 회원 탈퇴와 구분됩니다. 직원이 탈퇴하지 않은 경우 계정은 개인정보처리방침에 안내된 보유 기준에 따라 유지되며, 다른 사업장의 초대를 받아 소속 등록 절차를 완료하면 사업장 관련 기능을 다시 이용할 수 있습니다.
4. 회원 탈퇴 또는 소속 종료에 따른 데이터 처리는 제11조에 따릅니다.
5. 회사는 소속 종료, 소속 추가·변경 및 탈퇴에 관한 세부 절차를 근무 앱에서 안내합니다. 세부 절차는 관련 법령과 이 약관에 반할 수 없으며, 직원의 권리·의무에 중대한 영향을 미치는 변경은 제3조에 따라 처리합니다.

## 제11조 (직원 데이터 및 개인정보의 처리)

1. 소속 사업장은 근태, 근무스케줄, 업무 수행 및 급여 관련 기록을 인사·노무 관리 등의 목적으로 관련 법령에 따라 처리합니다.
2. 회사는 계정관리 및 서비스 제공을 위해 직접 처리하는 개인정보와 소속 사업장으로부터 위탁받아 처리하는 개인정보를 구분하여 관리합니다. 각 개인정보의 처리 목적, 항목, 보유기간 및 권리 행사 방법은 해당 개인정보처리방침과 필요한 동의서 등을 통해 안내합니다.
3. 회사가 소속 사업장으로부터 개인정보 처리 업무를 위탁받는 경우에는 위탁받은 업무의 범위에서만 해당 개인정보를 처리하며, 관련 법령에서 허용하는 경우를 제외하고 이를 다른 목적으로 이용하거나 제3자에게 제공하지 않습니다.
4. 회사는 이용계약 종료, 보유기간 경과 또는 처리 목적 달성 등으로 개인정보가 불필요하게 된 경우 지체 없이 파기합니다. 다만, 다른 법령에 따라 보존해야 하는 경우에는 해당 기간 동안 다른 개인정보와 분리하여 보관하고, 기간이 끝나면 파기합니다.
5. 직원의 회원 탈퇴 또는 소속 종료만으로 소속 사업장이 적법하게 보유하는 인사·노무 관련 기록이 모두 삭제되는 것은 아닙니다. 해당 기록의 보유 및 파기는 관련 법령과 소속 사업장의 적법한 처리 기준에 따르며, 회사가 위탁받아 보관하는 기록은 법령 및 위탁계약에 따라 처리합니다.
6. 직원은 관련 법령에 따라 개인정보의 열람, 정정·삭제, 처리정지 등을 요청할 수 있습니다. 회사는 직접 처리하는 개인정보에 관한 요청을 처리하고, 소속 사업장이 담당하는 개인정보에 관한 요청은 해당 사업장에 요청할 수 있도록 안내하거나 필요한 범위에서 협조합니다.
7. 이 약관에 대한 동의만으로 직원 데이터에 관한 법률상 권리가 회사 또는 소속 사업장에 이전되는 것은 아닙니다.

## 제12조 (지식재산권)

1. 근무 앱에 관한 소프트웨어, 디자인, 상표 등 지식재산권은 회사 또는 정당한 권리자에게 있습니다.
2. 직원은 근무 앱 이용에 필요한 범위에서 해당 소프트웨어와 콘텐츠를 이용할 수 있으며, 회사 또는 권리자의 허락 없이 이를 복제·배포·판매하는 등 권리를 침해해서는 안 됩니다.
3. 직원 데이터에 관한 권리와 처리는 제11조 및 관련 법령에 따릅니다.

## 제13조 (손해배상 및 책임)

